#!/usr/bin/env bash
# Export a built Company BI image + the deploy bundle, for transfer to a host with no build tools.
# Runs on the BUILD machine (needs docker). Does not touch any server.
#
#   export-image.sh --version <v> [--with-mysql] [--out DIR] [--allow-dirty]
#
# Produces in DIR (default deploy/companybi/dist/<v>/):
#   companybi_<v>_linux-amd64.tar          docker save of companybi:<v>
#   companybi_<v>_linux-amd64.tar.sha256   sha256sum format
#   companybi_deploy_<v>.tar.gz (+.sha256) compose.yaml, mysql/my.cnf, scripts/, .env.example, docs, release records
#   mysql_<tag>_linux-amd64.tar (+.sha256) only with --with-mysql: the MySQL image the stack needs
#   release_<v>.txt                        release record: commit, build time, image id, artifact hashes, flags
# Everything in dist/ is git-ignored. Transfer the files, then on the host:
#   sha256sum -c <file>.sha256  &&  scripts/install.sh|upgrade.sh --version <v> --image-tar <file>
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"   # deploy/companybi
VERSION=""; OUT=""; WITH_MYSQL=no; ALLOW_DIRTY=no
log() { printf '%s %s\n' "$(date '+%F %T')" "$*"; }
die() { log "ERROR: $*" >&2; exit 1; }
while [ $# -gt 0 ]; do
  case "$1" in
    --version) VERSION="${2:?}"; shift 2 ;;
    --out) OUT="${2:?}"; shift 2 ;;
    --with-mysql) WITH_MYSQL=yes; shift ;;
    --allow-dirty) ALLOW_DIRTY=yes; shift ;;
    -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done
[ -n "$VERSION" ] || die "--version is required"
case "$VERSION" in latest) die "refusing floating tag 'latest'" ;; esac
command -v docker >/dev/null || die "docker not found"
command -v sha256sum >/dev/null || die "sha256sum not found"
export MSYS_NO_PATHCONV=1

IMG="companybi:$VERSION"
docker image inspect "$IMG" >/dev/null 2>&1 || die "image $IMG not found; run scripts/build.sh first"
PLAT="$(docker image inspect -f '{{.Os}}/{{.Architecture}}' "$IMG")"
[ "$PLAT" = "linux/amd64" ] || die "image platform is $PLAT, expected linux/amd64"
DIRTY="$(docker image inspect -f '{{index .Config.Labels "com.companybi.git-dirty"}}' "$IMG")"
if [ "$DIRTY" = true ] && [ "$ALLOW_DIRTY" != yes ]; then die "image was built from a dirty tree; refusing to export (use --allow-dirty for a test export only)"; fi
LABEL_V="$(docker image inspect -f '{{index .Config.Labels "com.companybi.version"}}' "$IMG")"
[ "$LABEL_V" = "$VERSION" ] || die "image label version '$LABEL_V' != '$VERSION'"

OUT="${OUT:-$HERE/dist/$VERSION}"
mkdir -p "$OUT"
TAR="$OUT/companybi_${VERSION}_linux-amd64.tar"
ID_BEFORE="$(docker image inspect -f '{{.Id}}' "$IMG")"

log "docker save $IMG -> $TAR"
docker save "$IMG" -o "$TAR"
( cd "$OUT" && sha256sum "$(basename "$TAR")" > "$(basename "$TAR").sha256" )
TAR_SHA="$(awk '{print $1}' "$TAR.sha256")"
log "tar sha256: $TAR_SHA  ($(wc -c < "$TAR") bytes)"

# ---- optional MySQL image -------------------------------------------------------
MYSQL_LINE=""
if [ "$WITH_MYSQL" = yes ]; then
  MYSQL_IMG="$(sed -n 's/^COMPANY_BI_MYSQL_IMAGE=//p' "$HERE/.env.example" | head -1)"; MYSQL_IMG="${MYSQL_IMG:-mysql:8.4.5}"
  docker image inspect "$MYSQL_IMG" >/dev/null 2>&1 || { log "pulling $MYSQL_IMG (linux/amd64)"; docker pull --platform linux/amd64 "$MYSQL_IMG" >/dev/null; }
  mp="$(docker image inspect -f '{{.Os}}/{{.Architecture}}' "$MYSQL_IMG")"; [ "$mp" = linux/amd64 ] || die "$MYSQL_IMG is $mp, expected linux/amd64"
  MTAR="$OUT/mysql_${MYSQL_IMG#*:}_linux-amd64.tar"
  docker save "$MYSQL_IMG" -o "$MTAR"
  ( cd "$OUT" && sha256sum "$(basename "$MTAR")" > "$(basename "$MTAR").sha256" )
  MYSQL_LINE="mysql_image=$MYSQL_IMG  mysql_tar=$(basename "$MTAR")  mysql_tar_sha256=$(awk '{print $1}' "$MTAR.sha256")"
  log "mysql tar: $(basename "$MTAR")"
fi

# ---- deploy bundle (scripts + compose + docs; never .env, dist or secrets) ---------
BUNDLE="$OUT/companybi_deploy_${VERSION}.tar.gz"
STAGE="$(mktemp -d)"; trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/companybi"
( cd "$HERE" && tar --exclude='./dist' --exclude='./.env' --exclude='./image' --exclude='*.tar' --exclude='*.tar.gz' -cf - \
    compose.yaml .env.example mysql scripts README.md docs schema-compat.txt 2>/dev/null ) | tar -C "$STAGE/companybi" -xf -
[ -f "$OUT/companybi_${VERSION}.manifest" ] && cp "$OUT/companybi_${VERSION}.manifest" "$STAGE/companybi/"
chmod +x "$STAGE/companybi/scripts/"*.sh
tar -C "$STAGE" -czf "$BUNDLE" companybi
( cd "$OUT" && sha256sum "$(basename "$BUNDLE")" > "$(basename "$BUNDLE").sha256" )
log "bundle: $BUNDLE"

# ---- release record -----------------------------------------------------------------
ID_AFTER="$(docker image inspect -f '{{.Id}}' "$IMG")"
[ "$ID_BEFORE" = "$ID_AFTER" ] || die "image id changed during export"
REC="$OUT/release_${VERSION}.txt"
{
  echo "# Company BI release record  (generated by export-image.sh)"
  echo "version=$VERSION"
  echo "image=$IMG"
  echo "image_id=$ID_AFTER"
  echo "platform=$PLAT"
  echo "git_sha=$(docker image inspect -f '{{index .Config.Labels "com.companybi.git-sha"}}' "$IMG")"
  echo "git_dirty=$DIRTY"
  echo "build_time=$(docker image inspect -f '{{index .Config.Labels "org.opencontainers.image.created"}}' "$IMG")"
  echo "exported_at=$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  echo "artifact_tar=$(basename "$TAR")"
  echo "artifact_tar_sha256=$TAR_SHA"
  echo "artifact_tar_bytes=$(wc -c < "$TAR" | tr -d ' ')"
  echo "bundle=$(basename "$BUNDLE")"
  echo "bundle_sha256=$(awk '{print $1}' "$BUNDLE.sha256")"
  [ -z "$MYSQL_LINE" ] || echo "$MYSQL_LINE" | tr ' ' '\n' | sed '/^$/d'
  echo "docker_server_version=$(docker version -f '{{.Server.Version}}' 2>/dev/null || echo unknown)"
  echo "docker_image_store=$(docker info -f '{{.DriverStatus}}' 2>/dev/null | tr -d '\n' | cut -c1-80)"
  [ ! -f "$OUT/companybi_${VERSION}.manifest" ] || { echo "--- build manifest ---"; cat "$OUT/companybi_${VERSION}.manifest"; }
} > "$REC"
log "record: $REC"
log "DONE. Transfer these files:"
( cd "$OUT" && ls -1 "companybi_${VERSION}_linux-amd64.tar" "companybi_${VERSION}_linux-amd64.tar.sha256" "companybi_deploy_${VERSION}.tar.gz" "companybi_deploy_${VERSION}.tar.gz.sha256" "release_${VERSION}.txt" 2>/dev/null | sed 's/^/  /' )
